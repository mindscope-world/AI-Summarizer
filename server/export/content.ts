import type {ExportDocument} from '../../src/types';

/** Section headings in the language the summary is written in. */
export interface Labels {
  summary: string;
  takeaways: string;
  questions: string;
  notes: string;
  warnings: string;
  generatedBy: string;
}

const EN: Labels = {
  summary: 'Summary',
  takeaways: 'Key Takeaways',
  questions: 'Discussion & Revision Questions',
  notes: 'My Notes',
  warnings: 'Please double-check',
  generatedBy: 'Generated by LeaderForge Academic Summarizer',
};

const SW: Labels = {
  summary: 'Muhtasari',
  takeaways: 'Mambo Muhimu',
  questions: 'Maswali ya Majadiliano na Marudio',
  notes: 'Maelezo Yangu',
  warnings: 'Tafadhali hakiki',
  generatedBy: 'Imetolewa na LeaderForge Academic Summarizer',
};

export const labelsFor = (language?: string): Labels => (language === 'Swahili' ? SW : EN);

/** The small facts shown under the title, skipping any that were not supplied. */
export function metaLines(doc: ExportDocument): [string, string][] {
  const sw = doc.language === 'Swahili';
  const lines: [string, string][] = [];
  const add = (label: string, value?: string | number | null) => {
    const text = value === undefined || value === null ? '' : String(value).trim();
    if (text) lines.push([label, text]);
  };
  add(sw ? 'Kundi' : 'Category', doc.category);
  add(sw ? 'Lebo' : 'Tags', doc.tags?.join(', '));
  add(sw ? 'Tarehe' : 'Date', doc.createdDate);
  add(sw ? 'Mwandishi' : 'Author', doc.author);
  add(sw ? 'Taasisi' : 'Institution', doc.institution);
  add(sw ? 'Chanzo' : 'Source', doc.sourceName);
  add(sw ? 'Lugha' : 'Language', doc.language);
  add(sw ? 'Modeli' : 'Model', doc.model);
  if (doc.originalWordCount && doc.summaryWordCount) {
    const reduction = doc.reductionRate ? ` (${doc.reductionRate} ${sw ? 'fupi zaidi' : 'shorter'})` : '';
    add(sw ? 'Urefu' : 'Length', `${doc.originalWordCount} → ${doc.summaryWordCount} ${sw ? 'maneno' : 'words'}${reduction}`);
  }
  return lines;
}

/** Paragraphs of a free-text field (notes), without empty ones. */
export const paragraphsOf = (text?: string): string[] =>
  (text ?? '')
    .split(/\r?\n+/)
    .map((p) => p.trim())
    .filter(Boolean);

const CONTENT_TYPES = {
  pdf: 'application/pdf',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  txt: 'text/plain; charset=utf-8',
  md: 'text/markdown; charset=utf-8',
} as const;
export const contentTypeFor = (format: keyof typeof CONTENT_TYPES) => CONTENT_TYPES[format];

/** A file name made of safe ASCII only, from the document title. */
export function fileNameFor(title: string, format: string): string {
  const slug =
    title
      .normalize('NFKD')
      .replace(/[̀-ͯ]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '')
      .slice(0, 60) || 'summary';
  return `${slug}_summary.${format}`;
}
